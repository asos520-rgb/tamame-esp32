#!/usr/bin/env python3
"""Build a pinned 16px, 4bpp common-English/Chinese union font, offline.

Requires a local verified Noto Sans TC OTF, Node, and lv_font_conv 1.5.3.
Does not touch a private SDK, access the network, build firmware or flash.
"""
import argparse
import hashlib
import json
from pathlib import Path
import re
import subprocess
import tempfile

ROOT=Path(__file__).resolve().parents[1]
COMP=ROOT/'firmware-overlay/esp32/components/muse'
FONTS=COMP/'fonts'
FONT_SHA256='dce08bd4fd91aa8aa76ed8fea4b694c2dfb8550f67871e326843212ddbeb88b4'
FONT_URL='https://raw.githubusercontent.com/notofonts/noto-cjk/f8d157532fbfaeda587e826d4cd5b21a49186f7c/Sans/OTF/TraditionalChinese/NotoSansCJKtc-Regular.otf'

def primary_sets():
    # Big5 first-level ideographs: A440-C67E, 5401 characters.
    big5={bytes([lead,trail]).decode('big5')
          for lead in range(0xA4,0xC7)
          for trail in [*range(0x40,0x7F),*range(0xA1,0xFF)]
          if not (lead==0xC6 and trail>0x7E)}
    # GB2312 level-1 ideographs: B0A1-D7F9, 3755 characters.
    gb={bytes([lead,trail]).decode('gb2312')
        for lead in range(0xB0,0xD8) for trail in range(0xA1,0xFF)
        if not (lead==0xD7 and trail>0xF9)}
    assert len(big5)==5401 and len(gb)==3755
    return big5,gb

def ui_characters():
    # Include every current CJK literal (and comments conservatively).
    # Once the UI catalog is added, its C/C++/JSON text is covered here too.
    chars=set('English简体中文繁體中文')
    for p in COMP.rglob('*'):
        if p.is_file() and p.suffix in ('.c','.h','.cpp','.json','.def') and not ('fonts' in p.relative_to(COMP).parts or 'avatar' in p.relative_to(COMP).parts):
            chars.update(re.findall('[\u3400-\u9fff]',p.read_text()))
    return chars

def required_charset():
    big5,gb=primary_sets()
    existing=set((FONTS/'noto_tc_charset.txt').read_text())
    latin={chr(cp) for cp in range(0x20,0x7F)}|{chr(cp) for cp in range(0xC0,0x100)}|set('\u00a0\u00a1\u00a9\u00ae\u00b0\u00b7\u00bf')
    return ''.join(sorted(existing|big5|gb|latin|ui_characters()))

def generate(font,converter,node):
    if hashlib.sha256(font.read_bytes()).hexdigest()!=FONT_SHA256:raise ValueError('Font checksum mismatch')
    pkg=json.loads((converter.parent/'package.json').read_text())
    if pkg['name']!='lv_font_conv' or pkg['version']!='1.5.3':raise ValueError('Converter must be lv_font_conv 1.5.3')
    charset=required_charset()
    # Reject missing source cmap entries before rasterization; no .notdef fallback.
    script="const fs=require('fs'),ot=require(process.argv[1]),font=ot.loadSync(process.argv[2]);const chars=JSON.parse(fs.readFileSync(process.argv[3],'utf8'));const missing=Array.from(chars).filter(c=>font.charToGlyphIndex(c)===0);process.stdout.write(JSON.stringify(missing));"
    with tempfile.TemporaryDirectory() as tmp:
        d=Path(tmp);symbols=d/'symbols.json';symbols.write_text(json.dumps(charset))
        missing=json.loads(subprocess.run([node,'-e',script,str(converter.parent/'node_modules/opentype.js'),str(font),str(symbols)],check=True,capture_output=True,text=True).stdout)
        if missing:raise ValueError('Source font lacks codepoints: '+','.join(f'U+{ord(c):04X}' for c in missing))
        out=d/'font.c'
        subprocess.run([node,str(converter),'--font',str(font),'--size','16','--bpp','4','--format','lvgl','--lv-font-name','muse_font_noto_tc_16','--no-compress','--no-kerning','--lv-include','lvgl.h','--symbols',charset,'-o',str(out)],check=True)
        text=out.read_text();text=re.sub(r' \* Opts: .*\n',' * Generated by tools/prepare_multilingual_font.py; see NotoSansTC-OFL.txt.\n',text)
        # Preserve the source font's proportional Latin advances and full-width CJK.
        if len(re.findall(r'\.adv_w =',text))-1!=len(charset):raise ValueError('Generated glyph count mismatch')
        (FONTS/'muse_font_noto_tc_16.c').write_text('// Noto Sans TC by Adobe and Google; SIL OFL 1.1.\n'+text)
        (FONTS/'noto_tc_charset.txt').write_text(charset)
    big5,gb=primary_sets()
    report={'format':1,'strategy':'single deduplicated union; original symbols retained; 16px 4bpp uncompressed; natural proportional advances','font_url':FONT_URL,'font_sha256':FONT_SHA256,'converter':'lv_font_conv 1.5.3','big5_primary':len(big5),'gb2312_level1':len(gb),'primary_union':len(big5|gb),'ui_cjk_codepoints':len(ui_characters()),'total_codepoints':len(charset),'source_cmap_missing':0,'generated_glyphs':len(charset),'charset_sha256':hashlib.sha256(charset.encode()).hexdigest(),'font_c_sha256':hashlib.sha256((FONTS/'muse_font_noto_tc_16.c').read_bytes()).hexdigest(),'scope':'Defined common repertoire, not all Unicode. Rare characters, emoji and other scripts are not guaranteed. UI language selection is implemented with a restart; hardware acceptance remains pending.'}
    (FONTS/'multilingual-coverage.json').write_text(json.dumps(report,indent=2)+'\n')
    print(json.dumps(report,indent=2))

if __name__=='__main__':
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--font',type=Path,required=True);p.add_argument('--converter',type=Path,required=True);p.add_argument('--node',default='node');a=p.parse_args();generate(a.font,a.converter,a.node)
